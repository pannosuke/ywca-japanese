def main() -> None:
    for yokai in YOKAI:
        extra = LEVEL1.get(yokai["id"])
        if extra:
            yokai["stories"].append(extra)
    OUT.write_text(json.dumps({"schema": 1, "yokai": YOKAI}, ensure_ascii=False, indent=2) + "\n")
    print(OUT, len(YOKAI))


if __name__ == "__main__":
    main()
