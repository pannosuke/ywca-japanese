def q(prompt, right, wrongs):
    choices = [{"ruby": right, "correct": True}]
    for wrong in wrongs:
        choices.append({"ruby": wrong, "correct": False})
    return {"prompt_ruby": prompt, "choices": choices}


def story(text, questions, glosses):
    return {"level": 0, "text_ruby": text, "questions": questions, "glosses": glosses}


